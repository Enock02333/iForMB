from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import sparse
from sklearn.ensemble import IsolationForest
from sklearn.model_selection import train_test_split

from ifor_mb.evaluation.thresholds import select_threshold
from ifor_mb.models import IFMLPDetector
from .features import add_temporal_and_numeric_features, message_vectorizer, tabular_preprocessor
from .schema import resolve_schema

SEEDS = [13, 29, 47, 71, 101]


def load_frame(path: Path):
    frame = pd.read_csv(path)
    schema = resolve_schema(frame.columns)
    return frame, schema


def build_features(train, validation, test, schema):
    train = add_temporal_and_numeric_features(train, schema)
    validation = add_temporal_and_numeric_features(validation, schema)
    test = add_temporal_and_numeric_features(test, schema)
    tabular = tabular_preprocessor(schema)
    x_train_tab = tabular.fit_transform(train)
    x_validation_tab = tabular.transform(validation)
    x_test_tab = tabular.transform(test)
    text = message_vectorizer()
    x_train_text = text.transform(train[schema.message].astype(str))
    x_validation_text = text.transform(validation[schema.message].astype(str))
    x_test_text = text.transform(test[schema.message].astype(str))
    return (
        sparse.hstack([x_train_tab, x_train_text], format="csr"),
        sparse.hstack([x_validation_tab, x_validation_text], format="csr"),
        sparse.hstack([x_test_tab, x_test_text], format="csr"),
    )


def development_targets(x_train, seed):
    """Create transparent IF-derived development targets; never presented as external ground truth."""
    model = IsolationForest(n_estimators=300, max_samples=10_000, contamination="auto", random_state=seed, n_jobs=-1)
    label = model.fit_predict(x_train)
    return (label == -1).astype(int)


def run_synthetic_pipeline(input_path: Path, output_dir: Path, seed: int = 13):
    frame, schema = load_frame(input_path)
    indices = np.arange(len(frame))
    train_idx, temp_idx = train_test_split(indices, test_size=0.4, random_state=seed)
    validation_idx, test_idx = train_test_split(temp_idx, test_size=0.5, random_state=seed)
    train, validation, test = frame.iloc[train_idx], frame.iloc[validation_idx], frame.iloc[test_idx]
    x_train, x_validation, x_test = build_features(train, validation, test, schema)
    y_train = development_targets(x_train, seed)
    # The validation/test target is generated by a train-fitted IF developmental oracle.
    oracle = IsolationForest(n_estimators=300, max_samples=10_000, contamination="auto", random_state=seed, n_jobs=-1)
    oracle.fit(x_train)
    y_validation = (oracle.predict(x_validation) == -1).astype(int)
    y_test = (oracle.predict(x_test) == -1).astype(int)
    detector = IFMLPDetector(seed=seed).fit(x_train, y_train)
    validation_scores, _ = detector.score(x_validation)
    threshold = select_threshold(y_validation, validation_scores, max_fpr=0.001)
    detector.threshold_ = threshold["threshold"]
    result = detector.predict(x_test)
    output_dir.mkdir(parents=True, exist_ok=True)
    summary = {
        "dataset_role": "framework development and workflow demonstration",
        "independent_ground_truth": False,
        "records": len(frame),
        "seed": seed,
        "split_counts": {"train": len(train), "validation": len(validation), "test": len(test)},
        "threshold": threshold,
        "test_predicted_anomalies": int(result.predictions.sum()),
        "evidence_shape": list(result.evidence.shape),
        "warning": "Synthetic results measure agreement with a train-fitted development oracle and are not external detector-accuracy evidence.",
    }
    (output_dir / "synthetic-development-summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return summary
